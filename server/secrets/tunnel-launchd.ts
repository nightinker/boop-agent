/**
 * Files for a Cloudflare Tunnel that serves the secrets host and runs as a
 * launchd LaunchAgent, i.e. outside Boop.app: it starts at login and launchd
 * restarts it if it dies, so it doesn't care whether Boop restarts.
 *
 * Pure string builders; scripts/secrets-remote-setup.ts writes them.
 * They hold no credentials: cloudflared's own tunnel credentials JSON stays
 * where `cloudflared tunnel create` put it and is only referenced by path.
 */

export const SECRETS_TUNNEL_LABEL = "dev.boop.secrets-tunnel";

function xml(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

function yamlString(value: string): string {
  return JSON.stringify(value);
}

export interface CloudflaredConfigInput {
  /** Tunnel UUID or name (from `cloudflared tunnel create`). */
  tunnel: string;
  /** Path to the tunnel's credentials JSON (~/.cloudflared/<uuid>.json). */
  credentialsFile: string;
  /** Public hostname, e.g. secret.example.com. */
  hostname: string;
  /** Local port of Boop's secrets-only listener. */
  port: number;
}

/** A cloudflared config that routes ONLY the secrets hostname, 404 for anything else. */
export function cloudflaredSecretsConfig(input: CloudflaredConfigInput): string {
  return [
    "# Boop remote secret entry. Generated by npm run secrets:remote-setup.",
    `tunnel: ${yamlString(input.tunnel)}`,
    `credentials-file: ${yamlString(input.credentialsFile)}`,
    "ingress:",
    `  - hostname: ${yamlString(input.hostname)}`,
    `    service: http://127.0.0.1:${input.port}`,
    "  - service: http_status:404",
    "",
  ].join("\n");
}

export interface LaunchAgentInput {
  label?: string;
  /** Absolute path to the cloudflared binary. */
  cloudflaredPath: string;
  /** Absolute path to the cloudflared config written above. */
  configPath: string;
  /** Absolute path for stdout/stderr. */
  logPath: string;
}

/** ~/Library/LaunchAgents/<label>.plist: runs the tunnel at login and keeps it alive. */
export function cloudflaredLaunchAgentPlist(input: LaunchAgentInput): string {
  const label = input.label ?? SECRETS_TUNNEL_LABEL;
  const args = [input.cloudflaredPath, "tunnel", "--no-autoupdate", "--config", input.configPath, "run"];
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${xml(label)}</string>
  <key>ProgramArguments</key>
  <array>
${args.map((a) => `    <string>${xml(a)}</string>`).join("\n")}
  </array>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>ThrottleInterval</key>
  <integer>10</integer>
  <key>ProcessType</key>
  <string>Background</string>
  <key>StandardOutPath</key>
  <string>${xml(input.logPath)}</string>
  <key>StandardErrorPath</key>
  <string>${xml(input.logPath)}</string>
</dict>
</plist>
`;
}
